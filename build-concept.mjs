import {readFileSync,writeFileSync} from 'node:fs';
// Classic IIFE permits direct file:// use while retaining module sources for tests.
const core=JSON.parse(readFileSync('dist/evidence/downloads/core-data.json','utf8'));
const subset={equipment:core.equipment,observations:core.observations.filter(x=>Number.isFinite(x.value)&&['kg/t','Nm3/t','m3_unspecified/t'].includes(x.unit))};
const model=readFileSync('dist/concept-model.mjs','utf8').replace(/^export /gm,'');
const app=readFileSync('dist/concept.mjs','utf8').replace(/^import .*?;\r?\n/,'');
writeFileSync('dist/concept-standalone.js',`// Generated by node build-concept.mjs; edit concept-model.mjs and concept.mjs.\n(()=>{\n'use strict';\nconst CONCEPT_DATA=${JSON.stringify(subset)};\n${model}\n${app}\n})();\n`);
console.log('Direct-open concept bundle generated from source modules and evidence subset.');
